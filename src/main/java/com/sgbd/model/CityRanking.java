package com.sgbd.model;

public class CityRanking {
    private long pozitie;
    private String oras;
    private String tara;
    private double valoare;
    private String unitate;

    public long getPozitie() { return pozitie; }
    public void setPozitie(long pozitie) { this.pozitie = pozitie; }
    public String getOras() { return oras; }
    public void setOras(String oras) { this.oras = oras; }
    public String getTara() { return tara; }
    public void setTara(String tara) { this.tara = tara; }
    public double getValoare() { return valoare; }
    public void setValoare(double valoare) { this.valoare = valoare; }
    public String getUnitate() { return unitate; }
    public void setUnitate(String unitate) { this.unitate = unitate; }
}
